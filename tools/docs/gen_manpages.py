"""Generate the dot man pages from the command table (ADR-020, N0.4, N12).

  share/man/man1/dot.1            the domains by group, the family flags,
                                  shortcuts, deprecated names, exit codes
  share/man/man1/dot-<domain>.1   one page per domain: its objects and
                                  commands, each command's effect and flags

The commands come from lib/dot/data/commands.txt (the plugin manifests),
the family flags and exit codes from schemas/cli/flags.json, and the prose
of dot(1) from tools/docs/man/dot.1.in. The .TH date is the top CHANGELOG
heading's, so the output is reproducible.

    tools/docs/gen_manpages.py                 # rewrite share/man/man1
    tools/docs/gen_manpages.py --check         # exit 1 when a page is stale
    tools/docs/gen_manpages.py --outdir DIR    # write the pages under DIR
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TABLE = pathlib.Path("lib/dot/data/commands.txt")
MANDIR = pathlib.Path("share/man/man1")
TEMPLATE = pathlib.Path("tools/docs/man/dot.1.in")


def roff(text: str) -> str:
    """Escape for roff: backslashes, hyphens (true minus signs), leading dots."""
    text = text.replace("\\", "\\\\").replace("-", "\\-")
    return "\\&" + text if text[:1] in (".", "'") else text


def rows(root: pathlib.Path) -> list[list[str]]:
    return [line.split("|") for line in (root / TABLE).read_text().splitlines()
            if line and not line.startswith("#")]


def release(root: pathlib.Path) -> tuple[str, str]:
    data = (root / "defaults/.chezmoidata.toml").read_text()
    version = re.search(r'^dotfiles_version\s*=\s*"([^"]+)"', data, re.MULTILINE)
    heading = re.search(r"^## v\d+\.\d+\.\d+.*?(\d{4}-\d{2}-\d{2})", (root / "CHANGELOG.md").read_text(), re.MULTILINE)
    return (version.group(1) if version else "", heading.group(1) if heading else "1970-01-01")


def th(name: str, version: str, date: str) -> str:
    return f'.TH {name.upper()} 1 "{date}" "dotfiles v{version}" "User Commands"'


def flag_lines(flags: list[list[str]]) -> list[str]:
    out = []
    for long, short, value, summary in flags:
        spelled = f"\\-\\-{roff(long)}" + (f", \\-{short}" if short else "")
        out += [".TP", f".B {spelled}" + (f" \\fI{roff(value)}\\fR" if value else ""), roff(summary)]
    return out


def command_lines(row: list[str], flags: list[list[str]]) -> list[str]:
    key, legacy, effect, summary = row[1], row[2], row[3], row[4]
    state = f"Runs \\fBdot {roff(legacy)}\\fR until the domain is extracted." if legacy else "Planned; not built yet."
    out = [".TP", f".B dot {roff(key)}", f"{roff(summary)}. Effect: {effect}. {state}"]
    if flags:
        out += [".RS", *flag_lines(flags), ".RE"]
    return out


def by_type(table: list[list[str]], kind: str, prefix: str = "") -> list[list[str]]:
    """Records of one type, optionally only those whose key starts with PREFIX."""
    return [r for r in table if r[0] == kind and r[1].startswith(prefix)]


def flags_of(table: list[list[str]]) -> dict[str, list[list[str]]]:
    out: dict[str, list[list[str]]] = {}
    for r in by_type(table, "flag"):
        out.setdefault(r[1], []).append(r[2:6])
    return out


def entries(pairs: list[tuple[str, str]]) -> list[str]:
    """`.TP` entries from (tag, body) pairs."""
    return [line for tag, body in pairs for line in (".TP", tag, body)]


def domain_head(domain: str, dom: list[str], version: str, date: str) -> list[str]:
    return [f".\\\" Generated by tools/docs/gen_manpages.py from {TABLE}. Do not edit.",
            th(f"dot-{domain}", version, date), ".SH NAME", f"dot\\-{domain} \\- {roff(dom[4])}",
            ".SH SYNOPSIS", f".B dot {domain}", ".RI [ object ]", ".I verb", ".RI [ args ]",
            ".SH DESCRIPTION", f".B dot {domain}", f"alone runs \\fB{dom[2]}\\fR.",
            "Every command takes \\fB\\-\\-help\\fR; \\fBdot help\\fR lists every domain."]


def domain_page(domain: str, table: list[list[str]], version: str, date: str) -> str:
    dom = by_type(table, "dom", domain)[0]
    objects = [(f".B {roff(r[1].split(' ', 1)[1])}", f"{roff(r[4])}; alone it runs \\fB{r[2]}\\fR.")
               for r in by_type(table, "obj", domain + " ")]
    flags = flags_of(table)
    commands = [line for r in by_type(table, "cmd", domain + " ") for line in command_lines(r, flags.get(r[1], []))]
    aliases = [r for r in by_type(table, "alias") if r[3].split()[0] == domain]
    out = domain_head(domain, dom, version, date)
    out += [".SH OBJECTS", *entries(objects)] if objects else []
    out += [".SH COMMANDS", *commands]
    out += [".SH OTHER NAMES", *[line for r in aliases for line in alias_lines(r)]] if aliases else []
    return "\n".join([*out, ".SH SEE ALSO", ".BR dot (1)"]) + "\n"


def alias_lines(row: list[str]) -> list[str]:
    name, kind, target, until = row[1], row[2], row[3], row[4]
    what = {"shortcut": "Shortcut for", "deprecated": f"Exits 127 from {until}; use",
            "removed": "Removed; use"}[kind]
    return [".TP", f".B dot {roff(name)}", f"{what} \\fBdot {roff(target)}\\fR."]


def group_lines(table: list[list[str]]) -> list[str]:
    domains = {r[1]: r for r in by_type(table, "dom")}
    out = []
    for r in by_type(table, "grp"):
        out += [f".SS {roff(r[2])}", *entries([(f".BR dot\\-{d} (1)", roff(domains[d][4])) for d in r[3].split()])]
    return out


def family_flag(flag: dict) -> tuple[str, str]:
    short = f", \\-{flag['short']}" if flag.get("short") else ""
    return f".B \\-\\-{roff(flag['long'])}{short}", roff(flag["meaning"])


def main_sections(root: pathlib.Path, table: list[list[str]]) -> dict[str, str]:
    family = json.loads((root / "schemas/cli/flags.json").read_text())
    aliases = by_type(table, "alias")
    pages = ",\n".join(f".BR dot\\-{r[1]} (1)" for r in sorted(by_type(table, "dom")))
    return {"@DOMAINS@": "\n".join(group_lines(table)),
            "@FLAGS@": "\n".join(entries([family_flag(f) for f in family["flags"]])),
            "@EXIT@": "\n".join(entries([(f".B {c['code']}", roff(c["meaning"])) for c in family["exit_codes"]])),
            "@SHORTCUTS@": "\n".join(line for r in aliases if r[2] == "shortcut" for line in alias_lines(r)),
            "@ALIASES@": "\n".join(line for r in aliases if r[2] != "shortcut" for line in alias_lines(r)),
            "@PAGES@": pages}


def main_page(root: pathlib.Path, table: list[list[str]], version: str, date: str) -> str:
    text = (root / TEMPLATE).read_text().replace("@VERSION@", version).replace("@DATE@", date)
    for marker, body in main_sections(root, table).items():
        text = text.replace(marker, body)
    return text


def pages(root: pathlib.Path) -> dict[str, str]:
    table, (version, date) = rows(root), release(root)
    out = {"dot.1": main_page(root, table, version, date)}
    for domain in sorted(r[1] for r in table if r[0] == "dom"):
        out[f"dot-{domain}.1"] = domain_page(domain, table, version, date)
    return out


def check(outdir: pathlib.Path, want: dict[str, str]) -> int:
    stale = sorted(n for n, text in want.items() if not (outdir / n).is_file() or (outdir / n).read_text() != text)
    extra = sorted(p.name for p in outdir.glob("dot-*.1") if p.name not in want)
    for name in stale:
        print(f"FAIL: {MANDIR / name} is stale; run tools/docs/generate-manpage.sh", file=sys.stderr)
    for name in extra:
        print(f"FAIL: {MANDIR / name} is not generated by any manifest; remove it", file=sys.stderr)
    return 1 if stale or extra else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=pathlib.Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="fail when a committed page is stale")
    parser.add_argument("--outdir", type=pathlib.Path, help="write the pages under DIR")
    args = parser.parse_args(argv)
    outdir = args.outdir or args.root / MANDIR
    want = pages(args.root)
    if args.check:
        return check(outdir, want)
    outdir.mkdir(parents=True, exist_ok=True)
    for name, text in want.items():
        (outdir / name).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
