"""Generate the dot PowerShell cmdlets from the plugin manifests (ADR-020, N11).

Every built command becomes `<Verb>-Dot<Noun>`: the verb is its dot verb's
approved PowerShell verb (schemas/cli/verbs.json), the noun the domain and
object in title case (or their `ps_noun`). So `dot ai list` is `Get-DotAi`
and `dot secret key new` is `New-DotSecretKey`. Where verbs share a
PowerShell verb, ADR-020's rule applies: `list` and `show` are one `Get`
cmdlet whose `-Name` picks `show`; `status` appends `Status` to the noun;
any other pair on one noun (`set` and `apply`, `start` and `serve`) is an
error the CLI-contract lint already rejects. A destructive command asks
first (ShouldProcess, N16). Planned commands get no cmdlet until built.

    tools/docs/gen_cmdlets.py           # write share/powershell/DotCommands.psm1
    tools/docs/gen_cmdlets.py --check   # exit 1 when it is stale
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
MODULE = pathlib.Path("share/powershell/DotCommands.psm1")


def title(word: str) -> str:
    return word[:1].upper() + word[1:]


def noun(manifest: dict, command: dict) -> str:
    base = manifest.get("ps_noun") or title(manifest["domain"])
    if "object" not in command:
        return base
    obj = next(o for o in manifest.get("objects", []) if o["name"] == command["object"])
    return base + (obj.get("ps_noun") or title(obj["name"]))


def built(manifest: dict, command: dict) -> bool:
    """Runs today: through the plugin's entry unless planned, else a legacy route."""
    if "entry" in manifest:
        return not command.get("planned")
    return "legacy" in command


def cmdlets(root: pathlib.Path) -> list[dict]:
    """One entry per cmdlet: a built command, or a list and show merged."""
    ps = {v["name"]: v["powershell"] for v in json.loads((root / "schemas/cli/verbs.json").read_text())["verbs"]}
    entries: dict[str, dict] = {}
    for path in sorted((root / "plugins").glob("*/dot-plugin.toml")):
        manifest = tomllib.loads(path.read_text())
        for command in (c for c in manifest["commands"] if built(manifest, c)):
            suffix = "Status" if command["verb"] == "status" else ""
            name = f"{ps[command['verb']]}-Dot{noun(manifest, command)}{suffix}"
            words = " ".join(w for w in (manifest["domain"], command.get("object")) if w)
            add(entries.setdefault(name, {"name": name, "base": words, "runs": {}, "effect": "read"}), command)
    return sorted(entries.values(), key=lambda e: e["name"])


def add(entry: dict, command: dict) -> None:
    """Add a command to its cmdlet; only list and show may share one."""
    verbs = {command["verb"], *entry["runs"]}
    if command["verb"] in entry["runs"] or (entry["runs"] and verbs != {"list", "show"}):
        sys.exit(f"{entry['name']}: {entry['base']} {command['verb']} collides with "
                 f"{sorted(entry['runs'])} (ADR-020 N11)")
    entry["runs"][command["verb"]] = command["summary"]
    entry["effect"] = max(entry["effect"], command["effect"], key=EFFECTS.index)


EFFECTS = ["read", "write", "destructive"]


def call(entry: dict) -> str:
    base, runs = entry["base"], entry["runs"]
    if set(runs) == {"list", "show"}:
        return (f"if ($Name) {{ dot {base} show $Name @Arguments }} "
                f"else {{ dot {base} list @Arguments }}")
    return f"dot {base} {next(iter(runs))} @Arguments"


def function(entry: dict) -> str:
    destructive = entry["effect"] == "destructive"
    merged = set(entry["runs"]) == {"list", "show"}
    # -Name only by name, so `Get-DotX --json` is list's flag, not a name.
    binding = ", ".join(["SupportsShouldProcess, ConfirmImpact = 'High'"] * destructive + ["PositionalBinding = $false"] * merged)
    binding = f"[CmdletBinding({binding})]"
    body = call(entry)
    if destructive:
        body = f"if ($PSCmdlet.ShouldProcess('{entry['base']}', 'dot')) {{ {body} }}"
    params = "[Parameter(ValueFromRemainingArguments = $true)] [string[]] $Arguments = @()"
    if merged:
        params = "[string] $Name, " + params
    spelled = "; ".join(f"`dot {entry['base']} {verb}`: {summary}" for verb, summary in entry["runs"].items())
    return "\n".join([
        f"function {entry['name']} {{",
        "    <#",
        "    .SYNOPSIS",
        f"    {next(iter(entry['runs'].values()))}",
        "    .DESCRIPTION",
        f"    Runs {spelled}. Effect: {entry['effect']}; arguments pass through.",
        "    #>",
        f"    {binding}",
        # An empty default: without it, no arguments splat as one $null.
        f"    param({params})",
        f"    {body}",
        "}",
    ])


def module(root: pathlib.Path) -> str:
    entries = cmdlets(root)
    head = ["# dot PowerShell cmdlets. Generated by tools/docs/gen_cmdlets.py from the",
            "# plugin manifests (ADR-020, N11). Do not edit.", ""]
    body = [function(e) + "\n" for e in entries]
    exports = ["Export-ModuleMember -Function @(", *[f"    '{e['name']}'" for e in entries], ")"]
    return "\n".join(head + body + exports) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=pathlib.Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="fail when the module is stale")
    args = parser.parse_args(argv)
    text, path = module(args.root), args.root / MODULE
    if args.check:
        if not path.is_file() or path.read_text() != text:
            print(f"FAIL: {MODULE} is stale; run tools/docs/gen_cmdlets.py", file=sys.stderr)
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
