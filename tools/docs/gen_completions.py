"""Generate the dot shell completions from the command table (ADR-020, N0.4).

lib/dot/data/commands.txt, itself generated from plugins/*/dot-plugin.toml,
is the only input: every domain, object, verb, shortcut, flag and argument
hint comes from a manifest, so no completion list is written by hand. One
file per shell; each holds static data plus a few lines of lookup:

  bash        defaults/dot_local/share/bash-completion/completions/dot
  zsh         share/completions/zsh/_dot
  fish        defaults/dot_config/fish/completions/dot.fish
  nushell     defaults/dot_config/nushell/completions.nu
  powershell  share/completions/powershell/dot.ps1

`dot cli completion show <shell>` prints the committed file, so a shell
needs nothing but the file.

    tools/docs/gen_completions.py            # rewrite all five
    tools/docs/gen_completions.py --check    # exit 1 when one is stale
    tools/docs/gen_completions.py --outdir DIR   # write them under DIR
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from dataclasses import dataclass, field

ROOT = pathlib.Path(__file__).resolve().parents[2]
TABLE = pathlib.Path("lib/dot/data/commands.txt")
HEADER = ("Generated by tools/docs/gen_completions.py from lib/dot/data/commands.txt"
          " (the plugin manifests). Do not edit.")
TOP_FLAGS = [("help", "h", "", "Show help"), ("version", "V", "", "Print the version"),
             ("verbose", "v", "", "Verbose output")]


@dataclass
class Command:
    flags: list[tuple[str, str, str, str]] = field(default_factory=list)
    values: list[str] = field(default_factory=list)
    complete: str = ""


@dataclass
class Model:
    children: dict[str, list[tuple[str, str]]] = field(default_factory=dict)
    commands: dict[str, Command] = field(default_factory=dict)
    shortcuts: dict[str, str] = field(default_factory=dict)


def _rows(root: pathlib.Path) -> list[list[str]]:
    return [line.split("|") for line in (root / TABLE).read_text().splitlines()
            if line and not line.startswith("#")]


def _add_child(model: Model, key: str, summary: str) -> None:
    parent, _, word = key.rpartition(" ")
    model.children.setdefault(parent, []).append((word, summary))


def _load_row(model: Model, summaries: dict, row: list[str]) -> None:
    kind, key = row[0], row[1]
    if kind in ("dom", "obj", "cmd"):
        _add_child(model, key, row[4])
        summaries[key] = row[4]
    if kind == "cmd":
        model.commands[key] = Command()
    elif kind == "flag":
        model.commands[key].flags.append((row[2], row[3], row[4], row[5]))
    elif kind == "arg":
        model.commands[key].values, model.commands[key].complete = row[2].split(), row[3]
    elif kind == "alias" and row[2] == "shortcut":
        model.shortcuts[key] = row[3]


def load(root: pathlib.Path) -> Model:
    model, summaries = Model(), {}
    for row in _rows(root):
        _load_row(model, summaries, row)
    builtins = json.loads((root / "schemas/cli/domains.json").read_text())["builtins"]
    model.children[""] += [(name, summaries.get(target, target)) for name, target in model.shortcuts.items()]
    model.children[""] += [(name, f"Built-in: {name}") for name in builtins]
    return model


def flag_words(cmd: Command) -> list[str]:
    words = ["--help"]
    for long, short, _, _ in cmd.flags:
        words += [f"--{long}"] + ([f"-{short}"] if short else [])
    return words


def valued(cmd: Command, pattern: bool) -> list[str]:
    """Spellings of the flags that take a value: pattern ones, or the others."""
    return [s for long, short, value, _ in cmd.flags if value and (value == "pattern") == pattern
            for s in ([f"--{long}"] + ([f"-{short}"] if short else []))]


def q(text: str) -> str:
    """Single-quote for bash, zsh and fish."""
    return "'" + text.replace("'", "'\\''") + "'"


# ─── bash ─────────────────────────────────────────────────────────────────────


def bash_command_arm(path: str, cmd: Command) -> list[str]:
    lines = [f"    {q(path)} | {q(path)}\\ *)", f"      flags={q(' '.join(flag_words(cmd)))}"]
    if valued(cmd, True):
        lines.append(f"      patflags={q(' '.join(valued(cmd, True)))}")
    if valued(cmd, False):
        lines.append(f"      valflags={q(' '.join(valued(cmd, False)))}")
    if cmd.complete == "files":
        lines.append("      files=1")
    if cmd.values:
        lines.append(f"      [[ \"$path\" != {q(path)} ]] || values={q(' '.join(cmd.values))}")
    return lines + ["      ;;"]


def gen_bash(model: Model) -> str:
    out = [f"# dot bash completion. {HEADER}", "# shellcheck shell=bash disable=SC2207", "",
           "_dot_patterns() {",
           '  local f',
           '  for f in "${XDG_CONFIG_HOME:-$HOME/.config}"/ai/patterns/*.md; do',
           '    [[ -e "$f" ]] || continue',
           '    f="${f##*/}"',
           "    printf '%s\\n' \"${f%.md}\"",
           "  done",
           "}", "",
           "_dot() {",
           '  local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD - 1]}"',
           '  local path="" w i words="" values="" flags="--help" patflags="" valflags="" files=""',
           "  for ((i = 1; i < COMP_CWORD; i++)); do",
           '    w="${COMP_WORDS[i]}"',
           '    [[ "$w" == -* ]] || path="${path:+$path }$w"',
           "  done",
           '  case "${path%% *}" in']
    out += [f'    {name}) path="{target}${{path#{name}}}" ;;' for name, target in sorted(model.shortcuts.items())]
    out += ["  esac", '  case "$path" in']
    for path, kids in sorted(model.children.items()):
        out.append(f"    {q(path)}) words={q(' '.join(w for w, _ in kids))} ;;")
    top = " ".join(f"--{lng} -{s}" for lng, s, _, _ in TOP_FLAGS)
    out += ["  esac", f'  [[ -n "$path" ]] || flags={q(top)}', '  case "$path" in']
    for path, cmd in sorted(model.commands.items()):
        out += bash_command_arm(path, cmd)
    out += ["  esac",
            '  if [[ -n "$patflags" && " $patflags " == *" $prev "* ]]; then',
            '    COMPREPLY=($(compgen -W "$(_dot_patterns)" -- "$cur"))',
            '  elif [[ -n "$valflags" && " $valflags " == *" $prev "* ]]; then',
            "    COMPREPLY=()",
            '  elif [[ "$cur" == -* ]]; then',
            '    COMPREPLY=($(compgen -W "$flags" -- "$cur"))',
            "  else",
            '    COMPREPLY=($(compgen -W "$words $values" -- "$cur"))',
            '    [[ -z "$files" ]] || COMPREPLY+=($(compgen -f -- "$cur"))',
            "  fi",
            "}", "",
            "complete -F _dot dot", ""]
    return "\n".join(out)


# ─── zsh ──────────────────────────────────────────────────────────────────────


def zsh_items(pairs: list[tuple[str, str]]) -> str:
    return " ".join(q(f"{word}:{summary}") for word, summary in pairs)


def zsh_flags(cmd: Command) -> list[tuple[str, str]]:
    pairs = [("--help", "Show help")]
    for long, short, _, summary in cmd.flags:
        pairs += [(f"--{long}", summary)] + ([(f"-{short}", summary)] if short else [])
    return pairs


def zsh_command_arm(path: str, cmd: Command) -> list[str]:
    lines = [f"    {q(path)} | {q(path)}\\ *)", f"      flags_=({zsh_items(zsh_flags(cmd))})"]
    if valued(cmd, True):
        lines.append(f"      patflags_=({' '.join(valued(cmd, True))})")
    if valued(cmd, False):
        lines.append(f"      valflags_=({' '.join(valued(cmd, False))})")
    if cmd.complete == "files":
        lines.append("      files_=1")
    if cmd.values:
        lines.append(f"      [[ \"$path_\" != {q(path)} ]] || values_=({' '.join(cmd.values)})")
    return lines + ["      ;;"]


def gen_zsh(model: Model) -> str:
    out = ["#compdef dot", f"# dot zsh completion. {HEADER}", "",
           "_dot() {",
           '  local path_="" w i prev="${words[CURRENT-1]}" files_=""',
           "  local -a kids_ values_ flags_ patflags_ valflags_",
           "  flags_=('--help:Show help')",
           "  for ((i = 2; i < CURRENT; i++)); do",
           '    w="${words[i]}"',
           '    [[ "$w" == -* ]] || path_="${path_:+$path_ }$w"',
           "  done",
           '  case "${path_%% *}" in']
    out += [f'    {name}) path_="{target}${{path_#{name}}}" ;;' for name, target in sorted(model.shortcuts.items())]
    out += ["  esac", '  case "$path_" in']
    for path, kids in sorted(model.children.items()):
        out.append(f"    {q(path)}) kids_=({zsh_items(kids)}) ;;")
    top = [(f"--{lng}", s) for lng, _, _, s in TOP_FLAGS] + [(f"-{sh}", s) for _, sh, _, s in TOP_FLAGS]
    out += ["  esac", f'  [[ -n "$path_" ]] || flags_=({zsh_items(top)})', '  case "$path_" in']
    for path, cmd in sorted(model.commands.items()):
        out += zsh_command_arm(path, cmd)
    out += ["  esac",
            "  if (( ${patflags_[(Ie)$prev]} )); then",
            '    local d="${XDG_CONFIG_HOME:-$HOME/.config}/ai/patterns"',
            "    compadd -- ${${(f)\"$(command ls -1 \"$d\" 2>/dev/null)\"}%.md}",
            "  elif (( ${valflags_[(Ie)$prev]} )); then",
            "    _message 'value'",
            "  elif [[ \"$PREFIX\" == -* ]]; then",
            "    _describe -t options 'option' flags_",
            "  else",
            "    (( ${#kids_} )) && _describe -t commands 'command' kids_",
            "    (( ${#values_} )) && compadd -- $values_",
            "    [[ -z \"$files_\" ]] || _files",
            "  fi",
            "}", "",
            'if [[ "${funcstack[1]:-}" == _dot ]]; then',
            '  _dot "$@"',
            "elif (( $+functions[compdef] )); then",
            "  compdef _dot dot",
            "fi", ""]
    return "\n".join(out)


# ─── fish ─────────────────────────────────────────────────────────────────────


def fish_flag(path: str, flag: tuple[str, str, str, str]) -> str:
    long, short, value, summary = flag
    line = f"complete -c dot -n {q('__dot_in ' + q(path))} -l {long}"
    line += f" -s {short}" if short else ""
    if value == "pattern":
        line += " -x -a '(__dot_patterns)'"
    elif value:
        line += " -x"
    return line + f" -d {q(summary)}"


def fish_command(path: str, cmd: Command) -> list[str]:
    lines = [fish_flag(path, flag) for flag in cmd.flags]
    if cmd.values:
        lines.append(f"complete -c dot -n {q('__dot_at ' + q(path))} -a {q(' '.join(cmd.values))}")
    if cmd.complete == "files":
        lines.append(f"complete -c dot -n {q('__dot_in ' + q(path))} -F")
    return lines


def gen_fish(model: Model) -> str:
    out = [f"# dot fish completion. {HEADER}", "",
           "function __dot_path --description 'dot words before the cursor, flags dropped, shortcuts expanded'",
           "    set -l words",
           "    for t in (commandline -opc)[2..-1]",
           "        string match -q -- '-*' $t; or set -a words $t",
           "    end",
           "    switch \"$words[1]\""]
    for name, target in sorted(model.shortcuts.items()):
        out += [f"        case {name}", f"            set words {target} $words[2..-1]"]
    out += ["    end", "    string join ' ' -- $words", "end", "",
            "function __dot_at --description 'the words before the cursor are exactly this command'",
            "    set -l p (__dot_path)",
            "    test \"$p\" = \"$argv[1]\"", "end", "",
            "function __dot_in --description 'the words before the cursor start with this command'",
            "    set -l p (__dot_path)",
            "    test \"$p\" = \"$argv[1]\"; or string match -q -- \"$argv[1] *\" \"$p\"", "end", "",
            "function __dot_patterns --description 'AI steering patterns'",
            "    set -l dir $HOME/.config/ai/patterns",
            "    set -q XDG_CONFIG_HOME; and set dir $XDG_CONFIG_HOME/ai/patterns",
            "    for f in $dir/*.md",
            "        string replace -r '.*/(.*)\\.md$' '$1' -- $f",
            "    end", "end", "",
            "complete -c dot -f"]
    out += [f"complete -c dot -n {q('__dot_at ' + q(''))} -l {lng} -s {s} -d {q(d)}" for lng, s, _, d in TOP_FLAGS]
    out.append(f"complete -c dot -n {q('not __dot_at ' + q(''))} -l help -d {q('Show help')}")
    for path, kids in sorted(model.children.items()):
        out += [f"complete -c dot -n {q('__dot_at ' + q(path))} -a {word} -d {q(summary)}" for word, summary in kids]
    for path, cmd in sorted(model.commands.items()):
        out += fish_command(path, cmd)
    return "\n".join(out) + "\n"


# ─── nushell ──────────────────────────────────────────────────────────────────


def nu_str(text: str) -> str:
    return json.dumps(text)


def nu_flag(flag: tuple[str, str, str, str]) -> str:
    long, short, value, summary = flag
    spelled = f"--{long}" + (f"(-{short})" if short else "")
    if value == "pattern":
        spelled += ': string@"nu-complete dot patterns"'
    elif value:
        spelled += ": string"
    return f"    {spelled} # {summary}"


def nu_positional(name: str, cmd: Command, has_kids: bool) -> list[str]:
    """The first parameter: a subcommand, a declared value, or files."""
    if has_kids:
        return [f'    command?: string@{nu_str("nu-complete " + name)}']
    if cmd.values:
        return [f'    value?: string@{nu_str("nu-complete " + name)}']
    return ["    ...paths: path"] if cmd.complete == "files" else []


def nu_extern(model: Model, path: str) -> list[str]:
    name = f"dot {path}".strip()
    cmd = model.commands.get(path, Command())
    lines = [f"export extern {nu_str(name)} [", *nu_positional(name, cmd, path in model.children)]
    lines += [nu_flag(f) for f in cmd.flags]
    lines += ["    --help(-h) # Show help"] if path else [f"    --{lng}(-{s}) # {d}" for lng, s, _, d in TOP_FLAGS]
    if cmd.complete != "files":
        lines.append("    ...rest: string")
    return lines + ["]"]


def nu_completer(name: str, pairs: list[tuple[str, str]]) -> list[str]:
    items = [f"        {{ value: {nu_str(w)}, description: {nu_str(d)} }}" for w, d in pairs]
    return [f"def {nu_str('nu-complete ' + name)} [] {{", "    [", *items, "    ]", "}"]


def gen_nu(model: Model) -> str:
    out = [f"# dot nushell completion. {HEADER}", "",
           'def "nu-complete dot patterns" [] {',
           '    let dir = ($env.XDG_CONFIG_HOME? | default ($env.HOME | path join ".config") | path join "ai" "patterns")',
           '    if ($dir | path exists) { ls $dir | where name =~ \'\\.md$\' | get name | path parse | get stem } else { [] }',
           "}"]
    paths = sorted(set(model.children) | set(model.commands))
    for path in paths:
        name = f"dot {path}".strip()
        out.append("")
        if path in model.children:
            out += nu_completer(name, model.children[path])
        elif model.commands[path].values:
            out += nu_completer(name, [(v, "") for v in model.commands[path].values])
        out += nu_extern(model, path)
    for short, target in sorted(model.shortcuts.items()):
        out += ["", *[line.replace(f'"dot {target}"', f'"dot {short}"', 1) for line in nu_extern(model, target)]]
    return "\n".join(out) + "\n"


# ─── powershell ───────────────────────────────────────────────────────────────


def ps_str(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def ps_pairs(pairs: list[tuple[str, str]]) -> str:
    """An array of two-item arrays; the leading comma keeps a single pair from unrolling."""
    items = ", ".join(f"@({ps_str(w)}, {ps_str(d)})" for w, d in pairs)
    return f"@(, {items})" if len(pairs) == 1 else f"@({items})"


def ps_command(path: str, cmd: Command) -> str:
    flags = zsh_flags(cmd)
    fields = [f"Flags = {ps_pairs(flags)}",
              f"Values = @({', '.join(ps_str(v) for v in cmd.values)})",
              f"Files = ${'true' if cmd.complete == 'files' else 'false'}",
              f"PatternFlags = @({', '.join(ps_str(v) for v in valued(cmd, True))})",
              f"ValueFlags = @({', '.join(ps_str(v) for v in valued(cmd, False))})"]
    return f"    {ps_str(path)} = @{{ {'; '.join(fields)} }}"


def gen_pwsh(model: Model) -> str:
    out = [f"# dot PowerShell completion. {HEADER}", "",
           "$script:DotChildren = @{"]
    out += [f"    {ps_str(p)} = {ps_pairs(k)}" for p, k in sorted(model.children.items())]
    out += ["}", "$script:DotCommands = @{"]
    out += [ps_command(p, c) for p, c in sorted(model.commands.items())]
    out += ["}", "$script:DotShortcuts = @{"]
    out += [f"    {ps_str(n)} = {ps_str(t)}" for n, t in sorted(model.shortcuts.items())]
    top = [(f"--{lng}", d) for lng, _, _, d in TOP_FLAGS] + [(f"-{s}", d) for _, s, _, d in TOP_FLAGS]
    out += ["}", f"$script:DotTopFlags = {ps_pairs(top)}", ""]
    out.append(PS_BODY)
    return "\n".join(out) + "\n"


PS_BODY = r"""function Get-DotCompletion {
    param([string[]]$Words, [string]$Current)
    $path = @($Words | Where-Object { $_ -notlike '-*' })
    if ($path.Count -gt 0 -and $script:DotShortcuts.ContainsKey($path[0])) {
        $path = @($script:DotShortcuts[$path[0]] -split ' ') + @($path | Select-Object -Skip 1)
    }
    $key = $path -join ' '
    $prev = if ($Words.Count) { $Words[-1] } else { '' }
    $cmd = $null
    foreach ($name in $script:DotCommands.Keys) {
        if ($key -eq $name -or $key.StartsWith("$name ")) { $cmd = $script:DotCommands[$name]; $at = ($key -eq $name) }
    }
    if ($cmd -and $cmd.PatternFlags -contains $prev) {
        $dir = Join-Path ($env:XDG_CONFIG_HOME ?? (Join-Path $HOME '.config')) 'ai/patterns'
        return @(Get-ChildItem -Path $dir -Filter '*.md' -ErrorAction Ignore | ForEach-Object { , @($_.BaseName, 'AI pattern') })
    }
    if ($cmd -and $cmd.ValueFlags -contains $prev) { return @() }
    if ($Current -like '-*') {
        # Return each list as is: assigning it first would unroll a single pair.
        if ($key -eq '') { return $script:DotTopFlags }
        if ($cmd) { return $cmd.Flags }
        return , @('--help', 'Show help')
    }
    $items = @()
    if ($script:DotChildren.ContainsKey($key)) { $items += $script:DotChildren[$key] }
    if ($cmd -and $at) { $items += @($cmd.Values | ForEach-Object { , @($_, $_) }) }
    return $items
}

Register-ArgumentCompleter -Native -CommandName dot -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $words = @($commandAst.CommandElements | Select-Object -Skip 1 |
            Where-Object { $_.Extent.EndOffset -lt $cursorPosition -or ($_.Extent.EndOffset -eq $cursorPosition -and $wordToComplete -eq '') } |
            ForEach-Object { $_.ToString() })
    if ($wordToComplete -ne '' -and $words.Count -and $words[-1] -eq $wordToComplete) { $words = @($words | Select-Object -SkipLast 1) }
    Get-DotCompletion -Words $words -Current $wordToComplete |
        Where-Object { $_[0] -like "$wordToComplete*" } |
        ForEach-Object { [System.Management.Automation.CompletionResult]::new($_[0], $_[0], 'ParameterValue', $_[1]) }
}"""


TARGETS = {
    "bash": (pathlib.Path("defaults/dot_local/share/bash-completion/completions/dot"), gen_bash),
    "zsh": (pathlib.Path("share/completions/zsh/_dot"), gen_zsh),
    "fish": (pathlib.Path("defaults/dot_config/fish/completions/dot.fish"), gen_fish),
    "nu": (pathlib.Path("defaults/dot_config/nushell/completions.nu"), gen_nu),
    "pwsh": (pathlib.Path("share/completions/powershell/dot.ps1"), gen_pwsh),
}


def write(path: pathlib.Path, text: str) -> None:
    """Write with LF line ends; git checks .ps1 files out as CRLF (.gitattributes),
    and --check reads with universal newlines, so either compares equal."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=pathlib.Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="fail when a committed file is stale")
    parser.add_argument("--outdir", type=pathlib.Path, help="write each file under DIR by its basename")
    args = parser.parse_args(argv)
    model, stale = load(args.root), []
    for path, generate in TARGETS.values():
        text = generate(model)
        if args.outdir:
            write(args.outdir / path.name, text)
        elif args.check:
            target = args.root / path
            if not target.is_file() or target.read_text() != text:
                stale.append(str(path))
        else:
            write(args.root / path, text)
    for path in stale:
        print(f"FAIL: {path} is stale; run tools/docs/gen_completions.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
