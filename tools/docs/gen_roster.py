"""Generate every AI tool list from plugins/ai/roster.toml (plan v3, T0).

The roster is the only place a tool is named. This writes:

  plugins/ai/roster.json                          roster.v1, for dot-top
  lib/dot/data/ai-roster.sh                       data for lib/dot/ai-roster.sh
  defaults/dot_local/share/dot-ai-tui/roster_gen.go   the cockpit's fleet

and rewrites the line after each `roster: <kind>` marker comment in:

  plugins/ai/dot-plugin.toml                      `values = [...]`  (start, run)
  defaults/dot_local/bin/executable_tmux-ai       a case pattern    (deployed alone)

    tools/docs/gen_roster.py            # rewrite them all
    tools/docs/gen_roster.py --check    # exit 1 when one is stale
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
ROSTER = pathlib.Path("plugins/ai/roster.toml")
PINS = pathlib.Path("defaults/.chezmoidata.toml")
JSON_OUT = pathlib.Path("plugins/ai/roster.json")
SHELL_OUT = pathlib.Path("lib/dot/data/ai-roster.sh")
GO_OUT = pathlib.Path("defaults/dot_local/share/dot-ai-tui/roster_gen.go")
MARKED = [pathlib.Path("plugins/ai/dot-plugin.toml"),
          pathlib.Path("defaults/dot_local/bin/executable_tmux-ai")]
NOTICE = "Generated by tools/docs/gen_roster.py from plugins/ai/roster.toml. Do not edit."
# The generated files' own licence header. REUSE-IgnoreStart
LICENSE = ("SPDX-License-Identifier: Apache-2.0 OR MIT",
           "Copyright (c) 2015-2026 Sebastien Rousseau")
# REUSE-IgnoreEnd

# Cockpit and `dot ai list` sections in display order: the heading, and the
# role word the `dot ai` launcher prints beside each tool.
GROUPS = {
    "agents": ("Agents (autonomous)", "agent"),
    "coding": ("Coding (interactive)", "coding"),
    "general": ("General (prompt-based)", "general"),
    "local": ("Runtime (local)", "local"),
    "cloud": ("Cloud (platform)", "cloud"),
    "ecosystem": ("Ecosystem", "ecosystem"),
}
REQUIRED = ("name", "bin", "title", "summary", "group", "role")
MARKER = re.compile(r"^\s*# roster: (?P<kind>[a-z-]+)\s*$")


def load(root: pathlib.Path) -> list[dict]:
    """Read the roster and fill in the defaults; raise ValueError when invalid."""
    data = tomllib.loads((root / ROSTER).read_text())
    if data.get("schema") != "ai/roster.v1":
        raise ValueError(f"{ROSTER}: schema must be ai/roster.v1")
    pins = tomllib.loads((root / PINS).read_text()).get("ai_tools", {})
    tools, seen = [], set()
    for tool in data.get("tool", []):
        missing = [key for key in REQUIRED if not tool.get(key)]
        if missing:
            raise ValueError(f"{ROSTER}: {tool.get('name', '?')} lacks {', '.join(missing)}")
        if tool["group"] not in GROUPS:
            raise ValueError(f"{ROSTER}: {tool['name']} has unknown group {tool['group']}")
        tool = {"aliases": [], "processes": [tool["bin"]], "package": "", "native": "",
                "login": "", "chat": True, "fleet": True, **tool}
        if not isinstance(tool["login"], str):
            raise ValueError(f"{ROSTER}: {tool['name']} login must be a string of words")
        for key in [tool["name"], *tool["aliases"]]:
            if key in seen:
                raise ValueError(f"{ROSTER}: {key} names two tools")
            seen.add(key)
        if tool["package"] and tool["package"].split("[")[0] not in pins:
            raise ValueError(f"{ROSTER}: {tool['name']} package {tool['package']} has no pin"
                             f" in [ai_tools] ({PINS})")
        tools.append(tool)
    return tools


def by_group(tools: list[dict]) -> list[dict]:
    order = list(GROUPS)
    return sorted(tools, key=lambda tool: order.index(tool["group"]))


def chat_names(tools: list[dict]) -> list[str]:
    return [tool["name"] for tool in tools if tool["chat"]]


def render_json(tools: list[dict]) -> str:
    keys = ("name", "bin", "aliases", "title", "summary", "group", "role", "processes",
            "package", "native", "chat")
    doc = {"schema": "ai/roster.v1", "notice": NOTICE,
           "tools": [{key: tool[key] for key in keys} for tool in tools]}
    return json.dumps(doc, indent=2) + "\n"


def _sh_list(words: list[str]) -> str:
    return "(" + " ".join(_sh_word(word) for word in words) + ")"


def _sh_word(word: str) -> str:
    return word if re.fullmatch(r"[A-Za-z0-9@:/._+-]+", word) else "'" + word.replace("'", "'\\''") + "'"


def _sh_table(pairs: list[tuple[str, str]]) -> str:
    """One `key=value` line per pair, as a single ANSI-C quoted word ($'...',
    which bash 3.2 reads), so a table is one line of the generated file."""
    text = "".join(f"{key}={value}\n" for key, value in pairs)
    return "$'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def render_shell(tools: list[dict]) -> str:
    chat = [tool for tool in tools if tool["chat"]]
    eco = [tool for tool in tools if not tool["chat"] and tool["fleet"]]
    bin_of = [(key, tool["bin"]) for tool in tools for key in [tool["name"], *tool["aliases"]]]
    status = ["|".join([*GROUPS[t["group"]], t["title"], t["bin"], t["summary"]])
              for t in by_group(chat)]
    lines = [
        "#!/usr/bin/env bash",
        *(f"# {line}" for line in LICENSE),
        "# shellcheck disable=SC2034 # read by lib/dot/ai-roster.sh's callers",
        f"# {NOTICE}",
        "# Sourced by lib/dot/ai-roster.sh, which holds the lookups.",
        "",
        "# Agents, in roster order: what `dot ai start` takes, and their binaries.",
        f"AI_ROSTER_NAMES={_sh_list([t['name'] for t in chat])}",
        f"AI_ROSTER_BINS={_sh_list([t['bin'] for t in chat])}",
        "# Suite tools that are not agents.",
        f"AI_ROSTER_ECO_BINS={_sh_list([t['bin'] for t in eco])}",
        "# `dot ai list` rows: category|role|title|binary|summary.",
        f"AI_ROSTER_STATUS={_sh_list(status)}",
        "# name or alias=binary",
        f"AI_ROSTER_BIN_OF={_sh_table(bin_of)}",
        "# binary=mise package (a key of [ai_tools])",
        f"AI_ROSTER_PACKAGE_OF={_sh_table([(t['bin'], t['package']) for t in tools if t['package']])}",
        "# binary=native installer function",
        f"AI_ROSTER_NATIVE_OF={_sh_table([(t['bin'], t['native']) for t in tools if t['native']])}",
        "# binary=the command `dot ai login` runs (absent: <binary> --version)",
        f"AI_ROSTER_LOGIN_OF={_sh_table([(t['bin'], t['login']) for t in tools if t['login']])}",
    ]
    return "\n".join(lines) + "\n"


def render_go(tools: list[dict]) -> str:
    fleet = [t for t in by_group(tools) if t["fleet"]]
    roles = sorted({proc: t["role"] for t in tools for proc in t["processes"]}.items())
    out = [*(f"// {line}" for line in LICENSE),
           "",
           "// Code generated by tools/docs/gen_roster.py from plugins/ai/roster.toml. DO NOT EDIT.",
           "",
           "package main",
           "",
           "// fleet is the roster in display order, grouped by section.",
           "var fleet = []tool{"]
    out += [f'\t{{name: "{t["name"]}", bin: "{t["bin"]}", group: "{t["group"]}"}},' for t in fleet]
    out += ["}", "", "// rosterRoles maps each roster process name to its process-table role.",
            "var rosterRoles = map[string]string{"]
    width = max(len(proc) for proc, _ in roles) + 3
    out += [f'\t{json.dumps(proc) + ":":<{width}} "{role}",' for proc, role in roles]
    out += ["}"]
    return "\n".join(out) + "\n"


def marked_line(kind: str, indent: str, tools: list[dict]) -> str:
    names = chat_names(tools)
    if kind == "values":
        return indent + "values = [" + ", ".join(json.dumps(n) for n in names) + "]"
    if kind == "case":
        return indent + " | ".join(names) + ")"
    raise ValueError(f"unknown roster marker kind: {kind}")


def rewrite_marked(text: str, tools: list[dict], path: pathlib.Path) -> str:
    lines, count = text.split("\n"), 0
    for i, line in enumerate(lines[:-1]):
        match = MARKER.match(line)
        if match:
            indent = re.match(r"\s*", lines[i + 1]).group(0)
            lines[i + 1] = marked_line(match["kind"], indent, tools)
            count += 1
    if not count:
        raise ValueError(f"{path}: no `# roster:` marker")
    return "\n".join(lines)


def outputs(root: pathlib.Path) -> dict[pathlib.Path, str]:
    tools = load(root)
    files = {JSON_OUT: render_json(tools), SHELL_OUT: render_shell(tools), GO_OUT: render_go(tools)}
    for path in MARKED:
        files[path] = rewrite_marked((root / path).read_text(), tools, path)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    parser.add_argument("--root", type=pathlib.Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        files = outputs(args.root)
    except (ValueError, OSError, tomllib.TOMLDecodeError) as err:
        print(f"gen_roster: {err}", file=sys.stderr)
        return 2
    stale = [path for path, text in files.items()
             if not (args.root / path).is_file() or (args.root / path).read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path}", file=sys.stderr)
        if stale:
            print("Run tools/docs/gen_roster.py to regenerate.", file=sys.stderr)
        return 1 if stale else 0
    for path in stale:
        (args.root / path).write_text(files[path])
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
