"""Generate lib/dot/data/commands.txt, the command table bin/dot reads.

The table is the plugin manifests flattened into pipe-separated records, so
the dispatcher resolves ADR-020 spellings without parsing TOML:

  dom|<domain>|<default verb>|<legacy route or empty>|<summary>
  obj|<domain object>|<default verb>|<@domain or empty>|<summary>
  cmd|<domain [object] verb>|<legacy route or empty>|<effect>|<summary>
  run|<invocation with flags>|<legacy route>||
  leg|<legacy route>|<spelling>||   (the first spelling a route runs)
  grp|<group id>|<title>|<domains, space-separated>|  (help order)
  flag|<spelling>|<long>|<short>|<value>|<summary>
  arg|<spelling>|<words, space-separated>|<files or ai-patterns>|
  alias|<name>|<shortcut, deprecated or removed>|<target>|<until or empty>

A plugin with an `[entry]` runs its own commands: its routes are `@<domain>`
followed by the spelling, and bin/dot hands the words after the domain to
plugins/<domain>/dot-<domain>. Its commands marked `planned` are not built.
With `fallback`, the domain's own route is `@<domain>` too, so the domain
word alone and words its table does not take reach the entry; an object
with `fallback` names the entry too, so words after it that are not its
verbs reach the entry as well.

`cmd` records with an empty legacy are declared but not built yet. `run`
records come from old-name aliases whose target says more than a declared
spelling or one of its declared values (`dot tool list --nix` runs `tools`,
`dot help tour` runs `learn`), so every hint bin/dot prints runs what it
names.

It also writes lib/dot/data/commands.json, the same names as one JSON
catalog for agents and tools (`dot help --json`).

Route fragments (P2.1): each plugin's records are also written to
plugins/<domain>/commands.txt, its dom, obj, cmd, run (from its own
aliases), flag, arg and alias records, and the family's grp records to
lib/dot/data/groups.txt. lib/dot/table-merge.awk merges the fragments
back into the table: grp, then every dom/obj/cmd in domain order, the run
records (the first of each invocation), the leg records derived from
them, flag and arg, then alias. `merge()` is the same merge in Python; a
fragment set must merge to exactly the table above. The fragment format
is the contract a plugin's loader reads (ADR-020).

    tools/ci/cli_command_table.py            # rewrite the table and catalog
    tools/ci/cli_command_table.py --check    # exit 1 when either is stale
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
TABLE = pathlib.Path("lib") / "dot" / "data" / "commands.txt"
GROUPS = pathlib.Path("lib") / "dot" / "data" / "groups.txt"
FRAGMENT = "commands.txt"  # plugins/<domain>/commands.txt
CATALOG = pathlib.Path("lib") / "dot" / "data" / "commands.json"
HEADER = """\
# SPDX-License-Identifier: Apache-2.0 OR MIT
# Copyright (c) 2015-2026 Sebastien Rousseau
#
# Generated by tools/ci/cli_command_table.py from plugins/*/dot-plugin.toml.
# Do not edit: change the manifest and rerun the generator.
"""


def spelling(domain: str, command: dict) -> str:
    return " ".join(w for w in (domain, command.get("object"), command["verb"]) if w)


def route(domain: str, manifest: dict, command: dict) -> str:
    """What runs a command: its plugin's entry, a legacy route, or nothing yet."""
    if "entry" in manifest:
        return "" if command.get("planned") else f"@{spelling(domain, command)}"
    return command.get("legacy", "")


def domain_records(domain: str, manifest: dict) -> list[str]:
    bare = f"@{domain}" if manifest.get("entry", {}).get("fallback") else manifest.get("legacy", "")
    rows = [f"dom|{domain}|{manifest['default']}|{bare}|{manifest['summary']}"]
    rows += [f"obj|{domain} {o['name']}|{o['default']}|{f'@{domain}' if o.get('fallback') else ''}|{o['summary']}"
             for o in manifest.get("objects", [])]
    for command in manifest["commands"]:
        rows.append(f"cmd|{spelling(domain, command)}|{route(domain, manifest, command)}|"
                    f"{command['effect']}|{command['summary']}")
    return rows


def plugin_completion_records(domain: str, manifest: dict) -> list[str]:
    rows = []
    for command in manifest["commands"]:
        key = spelling(domain, command)
        rows += [f"flag|{key}|{f['long']}|{f.get('short', '')}|{f.get('value', '')}|{f['summary']}"
                 for f in command.get("flags", [])]
        args = command.get("args", {})
        if args:
            rows.append(f"arg|{key}|{' '.join(args.get('values', []))}|{args.get('complete', '')}|")
    return rows


def completion_records(manifests: dict) -> list[str]:
    """Flags and first-argument hints, for help and completions."""
    rows = []
    for domain, manifest in sorted(manifests.items()):
        rows += plugin_completion_records(domain, manifest)
    return rows


def alias_records(manifest: dict) -> list[str]:
    return [f"alias|{a['name']}|{a['kind']}|{a['target']}|{a.get('until', '')}"
            for a in manifest.get("aliases", [])]


def declared(manifests: dict) -> set[str]:
    """Every spelling a manifest declares: domains, objects and commands."""
    names = set(manifests)
    for domain, manifest in manifests.items():
        names |= {f"{domain} {o['name']}" for o in manifest.get("objects", [])}
        names |= {spelling(domain, c) for c in manifest["commands"]}
    return names


def declared_values(manifests: dict) -> set[str]:
    """`<command> <value>` for every value a command's args declare."""
    return {f"{spelling(d, c)} {v}" for d, m in manifests.items() for c in m["commands"]
            for v in c.get("args", {}).get("values", [])}


def plugin_run_records(manifest: dict, manifests: dict, names: set[str]) -> list[str]:
    """`run` records for one manifest's aliases (duplicates across
    manifests are dropped when the fragments merge)."""
    seen, rows = set(), []
    for alias in manifest.get("aliases", []):
        target = alias["target"]
        if alias["kind"] != "shortcut" and " " in target and target not in names | seen:
            seen.add(target)
            # A plugin with an entry runs the target itself, flags and all.
            owner = manifests.get(target.split()[0], {})
            route = f"@{target}" if "entry" in owner else alias.get("legacy", alias["name"])
            rows.append(f"run|{target}|{route}||")
    return rows


def run_records(manifests: dict) -> list[str]:
    names = declared(manifests) | declared_values(manifests)
    seen, rows = set(), []
    for manifest in manifests.values():
        for row in plugin_run_records(manifest, manifests, names):
            key = row.split("|")[1]
            if key not in seen:  # the first manifest to name an invocation wins
                seen.add(key)
                rows.append(row)
    return rows


def legacy_records(rows: list[str]) -> list[str]:
    seen, out = set(), []
    for row in rows:
        kind, key, legacy = row.split("|")[:3]
        if kind in ("cmd", "run") and legacy and not legacy.startswith("@") and legacy not in seen:
            seen.add(legacy)
            out.append(f"leg|{legacy}|{key}||")
    return out


def load(root: pathlib.Path) -> dict:
    return {p.parent.name: tomllib.loads(p.read_text())
            for p in sorted((root / "plugins").glob("*/dot-plugin.toml"))}


def load_family(root: pathlib.Path) -> dict:
    return json.loads((root / "schemas" / "cli" / "domains.json").read_text())


def group_records(family: dict) -> list[str]:
    members: dict[str, list[str]] = {}
    for domain in family["domains"]:
        members.setdefault(domain["group"], []).append(domain["name"])
    return [f"grp|{g['id']}|{g['title']}|{' '.join(members.get(g['id'], []))}|" for g in family["groups"]]


def catalog_command(domain: str, manifest: dict, command: dict) -> dict:
    entry = {"spelling": spelling(domain, command), "effect": command["effect"],
             "summary": command["summary"], "built": bool(route(domain, manifest, command))}
    for key in ("flags", "args", "output"):
        if key in command:
            entry[key] = command[key]
    return entry


def build_catalog(manifests: dict, family: dict) -> str:
    """The names as one JSON document (`dot help --json`); no version, so a
    release bump does not make it stale."""
    groups = {d["name"]: d["group"] for d in family["domains"]}
    domains = [{"name": name, "group": groups.get(name, ""), "summary": m["summary"], "default": m["default"],
                "objects": [{k: o[k] for k in ("name", "summary", "default")} for o in m.get("objects", [])],
                "commands": [catalog_command(name, m, c) for c in m["commands"]],
                "aliases": m.get("aliases", [])}
               for name, m in sorted(manifests.items())]
    doc = {"schema": "cli/catalog.v1", "builtins": family.get("builtins", []),
           "groups": family["groups"], "domains": domains}
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def build(manifests: dict, family: dict | None = None) -> str:
    rows = group_records(family) if family else []
    for domain, manifest in sorted(manifests.items()):
        rows += domain_records(domain, manifest)
    rows += run_records(manifests)
    rows += legacy_records(rows)
    rows += completion_records(manifests)
    for _, manifest in sorted(manifests.items()):
        rows += alias_records(manifest)
    return HEADER + "\n".join(rows) + "\n"


FRAGMENT_HEADER = """\
# SPDX-License-Identifier: Apache-2.0 OR MIT
# Copyright (c) 2015-2026 Sebastien Rousseau
#
# Generated by tools/ci/cli_command_table.py from {source}.
# Do not edit: change the manifest and rerun the generator.
"""


def fragment(domain: str, manifests: dict) -> str:
    """One plugin's records: what it declares, in table order."""
    manifest = manifests[domain]
    names = declared(manifests) | declared_values(manifests)
    rows = domain_records(domain, manifest)
    rows += plugin_run_records(manifest, manifests, names)
    rows += plugin_completion_records(domain, manifest)
    rows += alias_records(manifest)
    return FRAGMENT_HEADER.format(source=f"plugins/{domain}/dot-plugin.toml") + "\n".join(rows) + "\n"


def records(text: str) -> list[str]:
    return [ln for ln in text.splitlines() if ln and not ln.startswith("#")]


def merge(fragments: list[str]) -> list[str]:
    """The table's records from the groups and the fragments, in that
    order; lib/dot/table-merge.awk does the same at run time."""
    buckets: dict[str, list[str]] = {"grp": [], "body": [], "run": [], "comp": [], "alias": []}
    runs: set[str] = set()
    for text in fragments:
        for row in records(text):
            kind, key = row.split("|")[:2]
            if kind == "run":
                if key not in runs:
                    runs.add(key)
                    buckets["run"].append(row)
            else:
                bucket = {"dom": "body", "obj": "body", "cmd": "body", "flag": "comp", "arg": "comp"}.get(kind, kind)
                buckets[bucket].append(row)
    body = buckets["body"] + buckets["run"]
    return buckets["grp"] + body + legacy_records(body) + buckets["comp"] + buckets["alias"]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=pathlib.Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="fail when the table is stale")
    args = parser.parse_args(argv)
    outputs = expected(args.root)
    stale = [rel for rel, text in outputs.items()
             if not (args.root / rel).is_file() or (args.root / rel).read_text() != text]
    if args.check:
        for rel in stale:
            print(f"FAIL: {rel} is stale; run tools/ci/cli_command_table.py", file=sys.stderr)
        return 1 if stale else 0
    for rel, text in outputs.items():
        (args.root / rel).write_text(text)
    return 0


def expected(root: pathlib.Path) -> dict[pathlib.Path, str]:
    """What the table and the catalog should hold, from the manifests."""
    manifests, family = load(root), load_family(root)
    out = {TABLE: build(manifests, family), CATALOG: build_catalog(manifests, family),
           GROUPS: FRAGMENT_HEADER.format(source="schemas/cli/domains.json") + "\n".join(group_records(family)) + "\n"}
    for domain in sorted(manifests):
        out[pathlib.Path("plugins") / domain / FRAGMENT] = fragment(domain, manifests)
    return out


if __name__ == "__main__":
    sys.exit(main())
